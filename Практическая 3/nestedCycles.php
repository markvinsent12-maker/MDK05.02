<h3>Задача 1</h3>
<?php
// Внешний цикл: первый множитель от 1 до 9
for($i = 1; $i <= 9; $i++){
    // Внутренний цикл: второй множитель от 1 до 9
    for($j = 1; $j <= 9; $j++){
        // Выводим пример и результат
        echo "$i * $j = " . ($i * $j) . " | ";
    }
    // После завершения внутреннего цикла переходим на нвоую строку
    echo '<br>';
}
?>

