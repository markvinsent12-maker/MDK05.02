<h3>Задача 3</h3>
<?php
// Открываем таблицу и задаем границы
echo "<table border='1' cellpadding='5' cellspacing='0'>";
// Внешний цикл: строки(первый множитель)
for($i = 1; $i <= 9; $i++){
    echo "<tr>"; //Начало строки
    //Внутренний цикл: ячейки(вторй множитель)
    for($j = 1; $j <= 9; $j++){
        //Вычисляем произведение
        $result = $i * $j;
        //Выводим ячейку с результатом
        echo "<td>$result</td>";
    }
    echo "</tr>"; //Конец строки
}
echo '</table>'; //Закрываем таблицу
?>

<h3>Задача 4</h3>
<?php
echo "<table border='1' cellpadding='5' cellspacing='0'>";
$count = 0; // Счётчик, чтобы понимать, когда начинать новую строку
// Перебираем числа от 10 до 99
for ($i = 10; $i <= 99; $i++) {   
    // Если счётчик равен 0, начинаем новую строку
    if ($count == 0) {
        echo "<tr>";
    }   
    // Выводим ячейку с числом и его квадратом
    echo "<td>$i<sup>2</sup> = " . ($i * $i) . "</td>";   
    $count++; // Увеличиваем счётчик   
    // Если вывели 10 ячеек — закрываем строку и обнуляем счётчик
    if ($count == 10) {
        echo "</tr>";
        $count = 0;
    }
}
// Если остались незакрытые ячейки (в конце), закрываем строку и таблицу
if ($count > 0) {
    echo "</tr>";
}
echo "</table>";
?>

<h3>Задача 5</h3>
<?php
$a = 6; // Ширина
$b = 4; // Высота
echo "<h3>Прямоугольник с контуром</h3>";
echo "<pre>"; // Тег <pre> нужен, чтобы символы выводились ровно, как в блокноте
// Внешний цикл: строки
for ($i = 1; $i <= $b; $i++) {
    // Внутренний цикл: столбцы
    for ($j = 1; $j <= $a; $j++) {
        // Проверяем, является ли текущая позиция границей:
        // 1. Первая строка ($i == 1)
        // 2. Последняя строка ($i == $b)
        // 3. Первый столбец ($j == 1)
        // 4. Последний столбец ($j == $a)
        if ($i == 1 || $i == $b || $j == 1 || $j == $a) {
            echo "*"; // Контур
        } else {
            echo "0"; // Заливка
        }
    }
    echo "
"; // Конец строки
}
echo "</pre>";
?>